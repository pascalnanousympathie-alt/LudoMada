#!/usr/bin/env ruby
# Guard the Render staging Blueprint from accidental production/payment activation.
require "yaml"

path = ARGV.fetch(0, "render.yaml")
config = YAML.safe_load(File.read(path), aliases: false)
services = config.fetch("services")
raise "expected exactly one Render service" unless services.is_a?(Array) && services.length == 1
service = services.first

required_service = {
  "type" => "web",
  "name" => "ludomada-api-staging",
  "runtime" => "docker",
  "plan" => "free",
  "region" => "singapore",
  "branch" => "main",
  "healthCheckPath" => "/ready",
  "autoDeployTrigger" => "off"
}
required_service.each do |key, expected|
  actual = service[key]
  raise "#{key} must be #{expected.inspect}, got #{actual.inspect}" unless actual == expected
end

env = service.fetch("envVars").to_h { |item| [item.fetch("key"), item] }
required_false = %w[
  PAYMENTS_MVOLA_LIVE_ENABLED
  PAYMENTS_MVOLA_SANDBOX_ENABLED
  PAYMENTS_AIRTEL_SANDBOX_ENABLED
  PAYMENTS_BINANCE_LIVE_ENABLED
]
required_false.each do |key|
  entry = env[key]
  raise "#{key} must be explicitly configured" unless entry
  raise "#{key} must be the string false" unless entry["value"] == "false"
end

database_url = env["DATABASE_URL"]
raise "DATABASE_URL must be supplied as a protected value (sync: false)" unless database_url && database_url["sync"] == false

cors = env["CORS_ORIGINS"]
raise "CORS_ORIGINS must default to an empty deny-by-default allowlist" unless cors && cors["value"] == ""

jwt = env["JWT_SECRET"]
raise "JWT_SECRET must be generated by Render" unless jwt && jwt["generateValue"] == true
pool = env["PG_POOL_MAX"]
raise "PG_POOL_MAX must remain capped at 2 for free staging" unless pool && pool["value"] == "2"

puts "PASS: Render staging is isolated, manual-deploy, protected DB env, deny-by-default CORS, and payment-disabled"
